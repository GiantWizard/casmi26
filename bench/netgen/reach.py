"""Oracle reachability of class-3 answers by one edit of a linked neighbour's true structure."""
import sys, numpy as np, pandas as pd
sys.path.insert(0, '/Users/b/casmi26/fp'); sys.path.insert(0, '/Users/b/casmi26-repo/bench/obscure_np')
from edits import edit_products
from common import scorer_key
from rdkit import Chem
from rdkit.Chem.Descriptors import ExactMolWt
from collections import Counter
s, th = sys.argv[1], float(sys.argv[2]) if len(sys.argv) > 2 else 0.6
sol = pd.read_csv(f'{s}/solution.csv').set_index('molecule_id')
P = pd.read_parquet(f'{s}/pairs.parquet'); P = P[P.modcos >= th]
mass = {m: ExactMolWt(Chem.MolFromSmiles(x)) for m, x in sol.smiles.items()}
tkey = {m: scorer_key(x) for m, x in sol.smiles.items()}
nb = {}
for a, b in zip(P.a, P.b):
    nb.setdefault(a, set()).add(b); nb.setdefault(b, set()).add(a)
c3 = sol[sol.cls == 3].index
hit, sizes, how = 0, [], Counter()
for x in c3:
    cands = {}
    for y in nb.get(x, ()):
        for smi, name in edit_products(sol.smiles[y]).items():
            mm = Chem.MolFromSmiles(smi)
            if mm is not None and abs(ExactMolWt(mm) - mass[x]) < mass[x] * 1e-5:
                cands.setdefault(smi, name)
    keys = {}
    for smi, name in cands.items():
        k = scorer_key(smi)
        if k: keys.setdefault(k, name)
    sizes.append(len(keys))
    if tkey[x] in keys:
        hit += 1; how[keys[tkey[x]]] += 1
print(f'{s}: class-3 {len(c3)} | answer generated by one edit of a linked neighbour: {hit} ({hit / len(c3):.1%}) | '
      f'candidates per molecule median {np.median(sizes):.0f}, mean {np.mean(sizes):.0f}, max {max(sizes)}')
print('   by edit:', how.most_common())
