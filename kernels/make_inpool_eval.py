"""Generate an in-pool held-out eval notebook (set from bench/obscure_np/build_inpool_set.py, Kaggle dataset
giantwizard/casmi26-jc-inpool): the hidden test's dominant regime, timsTOF with the answer in the candidate pool and
no library spectrum of it.

Starts from make_onp_eval.py's notebook for the set (test draw swapped in, base2/c/c2/c2fix variants emitted) and:
  * cell 2: train.parquet becomes a copy without the held-out structures' rows (holdout_ik14.txt), written row group by
    row group to /tmp. Both engines read COMP/train.parquet, so both lose those library spectra.
  * cell 6: engine 2's candidate pool is COCONUT U ChEBI U train rows, so the held-out structures would vanish from
    it; eng_runner.py appends holdout_structs.parquet to the structures build_pool fingerprints. Engine 1's pool
    (pool_meta.parquet) is fixed and keeps them.

    python kernels/make_inpool_eval.py --draw 0 && kaggle kernels push -p kernels/jc-inpool-eval-d0
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ap = argparse.ArgumentParser()
ap.add_argument("--draw", type=int, default=0)
ap.add_argument("--dataset", default="giantwizard/casmi26-jc-inpool")
args = ap.parse_args()


def must_replace(text, old, new):
    assert text.count(old) == 1, (old[:80], text.count(old))
    return text.replace(old, new)


tmp = f"_inpool_tmp_d{args.draw}"
subprocess.run([sys.executable, str(ROOT / "kernels" / "make_onp_eval.py"), "--draw", str(args.draw),
                "--dataset", args.dataset, "--tag", tmp], check=True)
src = ROOT / "kernels" / f"jc-onp-eval-{tmp}-d{args.draw}"
meta = json.loads((src / "kernel-metadata.json").read_text())
nb = json.loads((src / meta["code_file"]).read_text())
cells = nb["cells"]
S = lambda i: "".join(cells[i]["source"])
put = lambda i, t: cells[i].update(source=t, outputs=[], execution_count=None)

OLD_LINK = """if not os.path.exists(os.path.join(_OC, 'train.parquet')):
    os.symlink(os.path.join(COMP, 'train.parquet'), os.path.join(_OC, 'train.parquet'))"""
NEW_LINK = """# ---- in-pool eval (make_inpool_eval.py): both engines read train.parquet minus the held-out structures ----
def _strip_train(src_path, dst, drop):
    import pyarrow as _pa, pyarrow.compute as _pc, pyarrow.parquet as _pq
    f = _pq.ParquetFile(src_path); tmp = dst + '.part'; kept = 0
    vs = _pa.array(sorted(drop))
    with _pq.ParquetWriter(tmp, f.schema_arrow, compression='zstd') as w:
        for _rg in range(f.num_row_groups):
            t = f.read_row_group(_rg)
            t = t.filter(_pc.invert(_pc.fill_null(_pc.is_in(t['inchikey14'], value_set=vs), False)))
            kept += t.num_rows; w.write_table(t)
    os.replace(tmp, dst)
    return f.metadata.num_rows, kept
_HOLD = set(open(find('holdout_ik14.txt')).read().split())
_IT = '/tmp/inpool_train/train.parquet'; os.makedirs(os.path.dirname(_IT), exist_ok=True)
_n0, _n1 = _strip_train(os.path.join(COMP, 'train.parquet'), _IT, _HOLD)
if os.path.lexists(os.path.join(_OC, 'train.parquet')):
    os.remove(os.path.join(_OC, 'train.parquet'))
os.symlink(_IT, os.path.join(_OC, 'train.parquet'))
os.environ['INPOOL_STRUCTS'] = find('holdout_structs.parquet')
print('in-pool eval:', len(_HOLD), 'held-out structures |', _n0, '->', _n1, 'train rows ->', _IT)"""
i2 = next(i for i, c in enumerate(cells) if c["cell_type"] == "code" and OLD_LINK in S(i))
put(i2, must_replace(S(i2), OLD_LINK, NEW_LINK))

# engine 2: keep the held-out structures in its candidate pool (patch the written eng_runner.py)
POOL_PATCH = '''
# ---- in-pool eval: engine 2 keeps proposing the held-out structures (its pool takes train structures from the library)
_r = open(os.path.join(ENG_DIR, 'eng_runner.py')).read()
_anchor = "    E.find = _find\\n"
assert _r.count(_anchor) == 1
_r = _r.replace(_anchor, _anchor + """    if os.environ.get('INPOOL_STRUCTS'):
        import pandas as _pd
        _hs = _pd.read_parquet(os.environ['INPOOL_STRUCTS'])
        _bp = E.build_pool
        def _build_pool(L, workers):
            L2 = dict(ik=np.concatenate([L['ik'], _hs.inchikey14.values.astype(object)]),
                      smi=np.concatenate([L['smi'], _hs.smiles.values.astype(object)]))
            return _bp(L2, workers)
        E.build_pool = _build_pool
        print('in-pool eval: engine 2 pool +', len(_hs), 'held-out structures', flush=True)
""")
open(os.path.join(ENG_DIR, 'eng_runner.py'), 'w').write(_r)
'''
i6 = next(i for i, c in enumerate(cells) if c["cell_type"] == "code" and "for _n, _src in ENG_FILES.items()" in S(i))
c6 = S(i6)
put(i6, must_replace(c6, "\nENG = {}\n", POOL_PATCH + "ENG = {}\n"))

slug = f"casmi26-jc-inpool-eval-d{args.draw}"
cells[0]["source"] = (f"# {slug}: in-pool held-out timsTOF eval (train rows of the answers removed). "
                      "Generated by kernels/make_inpool_eval.py. Offline evaluation only.\n\n") + S(0)
for c in cells:
    if c["cell_type"] == "code":
        compile("".join(c["source"]), "cell", "exec")
out = ROOT / "kernels" / f"jc-inpool-eval-d{args.draw}"
out.mkdir(exist_ok=True)
(out / f"{slug}.ipynb").write_text(json.dumps(nb, indent=1))
meta.update(id=f"giantwizard/{slug}", title=slug, code_file=f"{slug}.ipynb")
meta.pop("id_no", None)
(out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
for p in src.iterdir():
    p.unlink()
src.rmdir()
print("wrote", out, "| datasets:", meta["dataset_sources"][-1])
