"""Generate an "extra library" variant of an ONP eval notebook (lever: extra reference spectra).

Takes an eval notebook dir generated by kernels/make_onp_eval.py (e.g. kernels/jc-onp-eval-b-d0) and writes
kernels/<dir>-xlib, whose notebook appends giantwizard/casmi26-jc-extralib's extra_eval.parquet (public library
spectra of structures absent from train.parquet, eval molecules removed; build: bench/obscure_np/build_extralib.py)
to the train.parquet that engine 2 reads.

Where train.parquet is used, and what the variant does:
  * Engine 2 (cell 6, eng_runner -> casmi_engine.main) builds BOTH its spectral library and its candidate pool
    from train.parquet (pool = COCONUT U ChEBI/LIPID MAPS U every inchikey14/normalized_smiles in train), so
    concatenated rows make the extra structures searchable AND proposable there with no other change.
  * Engine 1 (cell 10, casmi.build.build_spec_cache) maps rows to structures through the shipped
    train_structs.parquet; unknown inchikey14s get sid = -1, which Library then indexes as the LAST structure
    (wrong mass, wrong parent for derivative generation, and the fe_v4 per-structure resources are sized to
    the shipped structures). Its candidates come only from the fixed pool_meta.parquet. Making extras work
    there means rebuilding pool fingerprints/fragments and all fe_v4 resources, so engine 1 keeps reading the
    ORIGINAL train.parquet. Extra structures reach the final list via engine 2 (RRF fusion, cell 19) and the
    simulator rerank of the fused list; engine 1's lib_max (PubChem gate, cell 17) is unchanged.

The concatenated file goes to /tmp (not /kaggle/working, so a Kaggle run does not save a 3 GB output),
written row group by row group (peak RAM ~ one row group).

    python kernels/make_extralib_eval.py jc-onp-eval-b-d0 jc-onp-eval-d2
    python kernels/make_extralib_eval.py jc-onp-eval-d2 --file extra_full.parquet   # no eval exclusion: never for eval
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ap = argparse.ArgumentParser()
ap.add_argument("dirs", nargs="+", help="eval notebook dirs under kernels/ (from make_onp_eval.py)")
ap.add_argument("--dataset", default="giantwizard/casmi26-jc-extralib")
ap.add_argument("--file", default="extra_eval.parquet", help="extra_eval.parquet (eval) or extra_full.parquet")
ap.add_argument("--suffix", default="xlib")
args = ap.parse_args()


def must_replace(text, old, new):
    assert text.count(old) == 1, (old[:80], text.count(old))
    return text.replace(old, new)


OLD_LINK = """if not os.path.exists(os.path.join(_OC, 'train.parquet')):
    os.symlink(os.path.join(COMP, 'train.parquet'), os.path.join(_OC, 'train.parquet'))"""
NEW_LINK = f"""# ---- extra library (make_extralib_eval.py): engine 2 reads train.parquet + {args.file}; engine 1 keeps the original ----
ORIG_TRAIN = os.path.join(COMP, 'train.parquet')
XLIB_FILE = find('{args.file}')
def _concat_train(dst):
    import pyarrow as _pa, pyarrow.parquet as _pq
    src = _pq.ParquetFile(ORIG_TRAIN); sch = src.schema_arrow
    xt = _pq.read_table(XLIB_FILE).select(sch.names).cast(sch)
    tmp = dst + '.part'
    with _pq.ParquetWriter(tmp, sch, compression='zstd') as w:
        for _rg in range(src.num_row_groups):
            w.write_table(src.read_row_group(_rg))
        w.write_table(xt, row_group_size=131072)
    os.replace(tmp, dst)
    return src.metadata.num_rows, xt.num_rows, len(set(xt.column('inchikey14').to_pylist()))
_XT = '/tmp/xlib_train/train.parquet'; os.makedirs(os.path.dirname(_XT), exist_ok=True)
_n0, _nx, _sx = _concat_train(_XT)
if os.path.lexists(os.path.join(_OC, 'train.parquet')):
    os.remove(os.path.join(_OC, 'train.parquet'))
os.symlink(_XT, os.path.join(_OC, 'train.parquet'))
print('extra library:', XLIB_FILE, '|', _n0, 'train rows +', _nx, 'extra rows (', _sx, 'structures ) ->', _XT)"""

OLD_E1 = "build_spec_cache(os.path.join(COMP, 'train.parquet'), 'work')"
NEW_E1 = "build_spec_cache(ORIG_TRAIN, 'work')   # xlib: engine 1 stays on the original library (see make_extralib_eval.py)"

for d in args.dirs:
    src = ROOT / "kernels" / d
    meta = json.loads((src / "kernel-metadata.json").read_text())
    nb = json.loads((src / meta["code_file"]).read_text())
    cells = nb["cells"]
    S = lambda i: "".join(cells[i]["source"])
    put = lambda i, t: cells[i].update(source=t, outputs=[], execution_count=None)
    i2 = next(i for i, c in enumerate(cells) if c["cell_type"] == "code" and OLD_LINK in S(i))
    put(i2, must_replace(S(i2), OLD_LINK, NEW_LINK))
    i10 = next(i for i, c in enumerate(cells) if c["cell_type"] == "code" and OLD_E1 in S(i))
    assert i10 > i2
    put(i10, must_replace(S(i10), OLD_E1, NEW_E1))
    # nothing else may read COMP/train.parquet before engine 2 except the smoke-switch symlink (it follows ours)
    slug = meta["id"].split("/")[1] + "-" + args.suffix
    cells[0]["source"] = (f"# {slug}: {meta['id'].split('/')[1]} + extra reference spectra ({args.file}, "
                          f"{args.dataset}) appended to engine 2's train.parquet\n"
                          "Generated by kernels/make_extralib_eval.py. Offline evaluation only.\n\n") + S(0)
    for c in cells:
        if c["cell_type"] == "code":
            compile("".join(c["source"]), f"{slug}", "exec")
    out = ROOT / "kernels" / f"{d}-{args.suffix}"
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{slug}.ipynb").write_text(json.dumps(nb, indent=1))
    meta.update(id=f"giantwizard/{slug}", title=slug, code_file=f"{slug}.ipynb")
    meta.pop("id_no", None)
    if args.dataset not in meta["dataset_sources"]:
        meta["dataset_sources"] = list(meta["dataset_sources"]) + [args.dataset]
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print("wrote", out)
