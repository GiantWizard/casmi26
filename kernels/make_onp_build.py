# Build. Seen = train_structs + MassSpecGym + GLACIER fine-tune labels.
OUT = '/kaggle/working/onp'
spectra = [f'{k}={GOT[k]}' for k in ('enveda180', 'gnps', 'massbank') if k in GOT]
