       '--train', TRAIN_STRUCTS, '--extra-seen', GOT['msg'], *FT_LABELS,
       '--spectra', *spectra,
       '--coconut', f'{H}/coconut.parquet', '--candidate-db', f'{H}/pool_keys.parquet',
